 note=note.strip()
 if item not in allowed[period] or action not in ("check","report","resolve"):return HTMLResponse("Μη έγκυρος έλεγχος.",400)
 if action=="check" and done not in (0,1):return HTMLResponse("Μη έγκυρη επιλογή.",400)
